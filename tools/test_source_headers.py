"""Header-only checks; no hardware simulation or external tools are launched."""
import ast
import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import source_headers as headers


class HeaderTests(unittest.TestCase):
    def test_styles_body_and_idempotence(self):
        for style, name, body in [('block', 'sample.scala', 'package example\n'),
                                  ('hash', 'sample.py', '#!/usr/bin/env python3\n"""Doc."""\nx=1\n'),
                                  ('hash', 'encoding.py', '#!/usr/bin/python3\n# coding: utf-8\nx=1\n'),
                                  ('block', 'build.mill', '//| mill-version: 1.1.7\n//| mill-jvm-version: system\npackage build\n'),
                                  ('html', 'sample.md', '# Title\n\nSummary.\n')]:
            with self.subTest(style=style, name=name):
                after = headers.add_header(body, name, style)
                offset = headers.prefix_length(body)
                self.assertEqual(after[:offset] + after[offset + len(headers.header(name, style)):], body)
                self.assertEqual(headers.add_header(after, name, style), after)
                self.assertEqual(after.count(headers.BEGIN), 1)
                if name.endswith('.py'):
                    self.assertEqual(ast.dump(ast.parse(body)), ast.dump(ast.parse(after)))

    def test_changed_header_is_rejected(self):
        stamped = headers.add_header('module T; endmodule\n', 'T.sv', 'block')
        with self.assertRaises(ValueError):
            headers.add_header(stamped.replace(headers.PROJECT, 'Wrong project', 1), 'T.sv', 'block')

    def test_coverage_rejects_unknown_and_missing(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(ValueError):
                headers.check(Path(tmp))
            root = Path(tmp)
            with patch.dict(headers.COVERAGE, {'example.py': 'hash'}, clear=True):
                path = root / 'example.py'
                path.write_text('x = 1\n')
                with self.assertRaises(ValueError):
                    headers.check(root)
                banner = headers.header('example.py', 'hash')
                path.write_text(banner + 'x = 1\n')
                self.assertEqual(headers.check(root)['inline'], 1)
                unknown = root / 'unclassified.txt'
                unknown.write_text('not classified\n')
                with self.assertRaises(ValueError):
                    headers.check(root)
                unknown.unlink()
                path.write_text(banner + banner + 'x = 1\n')
                with self.assertRaises(ValueError):
                    headers.check(root)
        headers.check()

    def test_generated_boundary_and_body(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            rtl = root / 'build' / 'new' / 'rtl'
            rtl.mkdir(parents=True)
            path = rtl / 'Example.sv'
            body = '// Generated by CIRCT\nmodule Example; endmodule\n'
            path.write_text(body)
            with patch.object(headers, 'ROOT', root):
                self.assertEqual(headers.stamp_generated(rtl), 1)
                after = path.read_text()
                banner = headers.header(path.name, 'block', headers.generated_attribution(), True)
                self.assertEqual(after, banner + body)
                headers.stamp_generated(rtl)
                self.assertEqual(path.read_text(), after)
                with self.assertRaises(ValueError):
                    headers.stamp_generated(root / 'rtl')
                (rtl / 'linked.sv').symlink_to(path)
                with self.assertRaises(ValueError):
                    headers.stamp_generated(rtl)

    def test_emitter_real_closure_hook(self):
        root = headers.ROOT
        emitter = root / 'tools' / 'emit_sv.py'
        if not emitter.exists():
            self.skipTest('Catalogue has no RTL generator')
        tree = ast.parse(emitter.read_text())
        closure = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in ('product_closure', 'closure'))
        first = closure.body[0]
        self.assertIsInstance(first, ast.Expr)
        self.assertIsInstance(first.value, ast.Call)
        self.assertEqual(first.value.func.id, 'stamp_generated')
        # Exercise the actual existing closure on copies of its bundled modules.
        spec = importlib.util.spec_from_file_location('header_test_emitter', emitter)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        bundled = list(root.glob('rtl/*/*/*.sv'))
        self.assertTrue(bundled)
        with tempfile.TemporaryDirectory() as tmp:
            test_root = Path(tmp)
            target = test_root / 'build' / 'test' / 'rtl'
            target.mkdir(parents=True)
            bodies = {}
            for source in bundled:
                text = source.read_text()
                banner = headers.header(source.relative_to(root).as_posix(), 'block', generated=True)
                self.assertTrue(text.startswith(banner))
                body = text[len(banner):]
                bodies[source.name] = body
                (target / source.name).write_text(body)
            with patch.object(headers, 'ROOT', test_root), patch.object(module, 'ROOT', test_root):
                selected = getattr(module, closure.name)(target)
            self.assertEqual({p.name for p in selected}, set(bodies))
            for path in target.glob('*.sv'):
                banner = headers.header(path.name, 'block', headers.generated_attribution(), True)
                self.assertEqual(path.read_text(), banner + bodies[path.name])


if __name__ == '__main__':
    unittest.main()
